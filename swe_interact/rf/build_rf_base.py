#!/usr/bin/env python3
"""Rebuild a swe-atlas RF environment image (ghcr.io/scaleapi/swe-atlas:*, amd64-only, history scrubbed) for arm64.

The swe-atlas images record no build instructions ("created by buildkit"), so tools/reconstruct.py does not apply.
Instead the image is reconstructed from its filesystem:

  1. base:      the public base image is identified by an exact diff_id prefix match (find_base.py); the arm64 build
                uses the same multi-arch tag.
  2. apt:       the final dpkg package set minus the base's is installed natively (x86-only names dropped).
  3. transplant: every file added after the base layers is copied from the official image into a tarball, except
                (a) files owned by dpkg packages (reinstalled natively), (b) ELF objects (architecture-specific;
                listed in report.json and regenerated by the per-repository recipe), (c) Python site-packages
                trees (reinstalled at the exact versions, see 4), (d) caches, logs, apt/dpkg state, uv-managed Pythons.
                This carries the repository (squashed single-commit .git), Go module caches, pure-JS node_modules,
                configuration, entrypoints and data directories unchanged.
  4. python:    each site-packages directory's distributions are reinstalled with the interpreter that owns it, pinned
                to the official versions with --no-deps; editable installs are reinstalled from the transplanted
                source. uv-managed interpreters and venvs built on them (the verifier's /opt/venv) are recreated.
  5. recipe:    rf/recipes/<repo>.sh (optional) rebuilds whatever the report lists as missing native pieces (go-installed
                tools, npm native modules / platform packages, compiled build trees), run as the last RUN step.
  6. config:    ENV, WORKDIR, ENTRYPOINT, CMD, USER, LABELs from the official image config.

Output: work/rf/<name>/ctx/{Dockerfile,transplant.tar,py-*.txt,...}, work/rf/<name>/report.json; image
bdqnghi/swe-interact-base:<name>, pushed with --push.

Usage: build_rf_base.py <task> [--no-build] [--push] [--keep-official]
"""
import argparse, io, json, os, re, shlex, shutil, subprocess, sys, tarfile, tempfile, time
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))
import build as B  # noqa: E402
import find_base as FB  # noqa: E402

DROP_PREFIX = ("var/lib/dpkg/", "var/lib/apt/", "lib/apk/", "etc/apk/world", "var/cache/apk/", "var/cache/", "var/log/", "tmp/", "root/.cache/", "proc/", "sys/",
               "dev/", "run/", "etc/ld.so.cache", "etc/alternatives/", "usr/share/doc/", "usr/share/man/",
               "root/.local/share/uv/", "root/.local/bin/uv", "root/.local/bin/uvx", "root/.local/bin/python3",
               "etc/hostname", "etc/hosts", "etc/resolv.conf", ".dockerenv", "root/.wget-hsts",
               "root/.python_history", "root/.npm/_cacache/", "root/.npm/_logs/", "usr/local/share/.cache/")
X86_PKG = re.compile(r"(x86-64|amd64|i386|x86_64|:amd64$|^libc6-dev-i386|^lib32|^libx32|^gcc-multilib|^g\+\+-multilib)")
SITE_RE = re.compile(r"^(.*?/(?:site|dist)-packages)/")
DIST_RE = re.compile(r"^(.*?/(?:site|dist)-packages)/([^/]+)-([^/-]+)\.dist-info/$")


def sh(cmd, **kw):
    return subprocess.run(cmd, shell=isinstance(cmd, str), capture_output=True, text=True, **kw)


def dpkg_status(text):
    pk = {}
    for block in text.split("\n\n"):
        m = re.search(r"^Package: (\S+)", block, re.M)
        a = re.search(r"^Architecture: (\S+)", block, re.M)
        s = re.search(r"^Status: .* installed$", block, re.M)
        v = re.search(r"^Version: (\S+)", block, re.M)
        if m and s:
            pk[m.group(1)] = (v.group(1) if v else "", a.group(1) if a else "")
    return pk


def is_elf(head):
    """Architecture-specific binaries: ELF objects and ar archives (static libs, Rust rlibs)."""
    return head[:4] == b"\x7fELF" or head[:8] == b"!<arch>\n"


def apk_status(text):
    """Alpine: /lib/apk/db/installed -> {pkg: (version, arch)}."""
    pk = {}
    for block in text.split("\n\n"):
        m = re.search(r"^P:(\S+)", block, re.M)
        v = re.search(r"^V:(\S+)", block, re.M)
        a = re.search(r"^A:(\S+)", block, re.M)
        if m:
            pk[m.group(1)] = (v.group(1) if v else "", a.group(1) if a else "")
    return pk


def apk_owned_from(text):
    owned, d = set(), ""
    for line in text.splitlines():
        if line.startswith("F:"):
            d = line[2:]
        elif line.startswith("R:"):
            owned.add(f"{d}/{line[2:]}" if d else line[2:])
    return owned


def analyse(image, nbase, work):
    """Stream `docker save` layers: paths touched after the base, dpkg state before/after; then stream the final
    filesystem (`docker export`) and write transplant.tar."""
    savep = work / "image.tar"
    if not savep.exists():
        subprocess.run(["docker", "save", "-o", str(savep), image], check=True)
    outer = tarfile.open(savep)
    manifest = json.load(outer.extractfile("manifest.json"))[0]
    cfg = json.load(outer.extractfile(manifest["Config"]))
    touched = set()
    dpkg_base = dpkg_final = apk_base = apk_final = None
    for i, lp in enumerate(manifest["Layers"]):
        try:
            inner = tarfile.open(fileobj=outer.extractfile(lp), mode="r|*")
        except tarfile.ReadError:
            continue
        for m in inner:
            name = m.name.lstrip("./")
            if name == "var/lib/dpkg/status" and m.isfile():
                txt = inner.extractfile(m).read().decode(errors="replace")
                if i < nbase:
                    dpkg_base = txt
                dpkg_final = txt
            if name == "lib/apk/db/installed" and m.isfile():
                txt = inner.extractfile(m).read().decode(errors="replace")
                if i < nbase:
                    apk_base = txt
                apk_final = txt
            if i >= nbase and not os.path.basename(name).startswith(".wh."):
                touched.add(name.rstrip("/"))
    outer.close()
    if apk_final is not None:  # Alpine
        return cfg, touched, apk_status(apk_base or ""), apk_status(apk_final), apk_final
    return cfg, touched, dpkg_status(dpkg_base or ""), dpkg_status(dpkg_final or ""), None


def dpkg_owned(container):
    """All paths listed by dpkg for installed packages in the official image (read without executing anything)."""
    tmp = tempfile.mkdtemp()
    subprocess.run(f"docker cp {container}:/var/lib/dpkg/info - | tar x -C {tmp}", shell=True, check=True)
    owned = set()
    for f in Path(tmp, "info").glob("*.list"):
        for line in f.read_text(errors="replace").splitlines():
            p = line.strip().lstrip("/")
            if p:
                owned.add(p)
                for a, b in (("bin/", "usr/bin/"), ("sbin/", "usr/sbin/"), ("lib/", "usr/lib/")):
                    if p.startswith(a):
                        owned.add(b + p[len(a):])
    shutil.rmtree(tmp)
    return owned


def transplant(container, touched, owned, ctx, report):
    """Write ctx/transplant.tar from `docker export` (final merged filesystem), filtered."""
    out = tarfile.open(ctx / "transplant.tar", "w", format=tarfile.PAX_FORMAT)
    elf, dropped_owned, dropped_site, x86_text = [], 0, Counter(), []
    go_tools = {}
    rust = {}
    dists = defaultdict(dict)       # site dir -> {name: version}
    direct = {}                     # site dir/name -> direct_url json
    pth = defaultdict(list)
    kept = Counter()
    p = subprocess.Popen(["docker", "export", container], stdout=subprocess.PIPE)
    tin = tarfile.open(fileobj=p.stdout, mode="r|")
    for m in tin:
        name = m.name.lstrip("./").rstrip("/")
        if not name or name not in touched:
            continue
        if name.startswith(DROP_PREFIX) or (name + "/").startswith(DROP_PREFIX):
            continue
        rm_ = re.match(r"^(.*rustup)/toolchains/([^/]+)$", name)
        if rm_ and m.isdir():
            rust["home"], _ = rm_.group(1), rust.setdefault("toolchains", []).append(rm_.group(2))
        if re.match(r"^.*rustup/", name):
            continue  # toolchains are reinstalled natively (see render)
        if re.match(r"^(.*cargo)/\.crates2\.json$", name) and m.isfile():
            rust["crates2"] = json.loads(tin.extractfile(m).read() or b"{}")
            rust["cargo_home"] = name.rsplit("/", 1)[0]
        if re.match(r"^.*cargo/bin/", name):
            continue
        if name in owned and not name.startswith("etc/"):
            dropped_owned += 1  # reinstalled by the package manager (including distro python3-* modules)
            continue
        sm = SITE_RE.match(name + ("/" if m.isdir() else ""))
        if sm:
            dm = DIST_RE.match(name + "/") if m.isdir() else None
            if dm:
                dists[dm.group(1)][dm.group(2)] = dm.group(3)
            if name.endswith(".dist-info/direct_url.json") and m.isfile():
                direct[name.rsplit("/", 1)[0]] = json.loads(tin.extractfile(m).read() or b"{}")
            if name.endswith(".pth") and m.isfile() and name.count("/") == sm.group(1).count("/") + 1:
                pth[sm.group(1)].append(os.path.basename(name))
            dropped_site[sm.group(1)] += 1
            continue
        if name in owned and not name.startswith("etc/"):
            dropped_owned += 1
            continue
        if m.isfile():
            data = tin.extractfile(m).read()
            if is_elf(data[:8]) and not keep_elf(name):
                elf.append(name)
                gi = go_buildinfo(data)
                if gi:
                    go_tools[name] = gi
                continue
            if b"x86_64-linux-gnu" in data[:2_000_000] and len(x86_text) < 400:
                x86_text.append(name)
            out.addfile(m, io.BytesIO(data))
        else:
            out.addfile(m)
        kept[name.split("/")[0]] += 1
    p.wait()
    out.close()
    report.update(elf_dropped=elf, go_tools=go_tools, rust=rust, dpkg_owned_dropped=dropped_owned, site_dropped=dict(dropped_site),
                  x86_text_files=x86_text, kept_top=dict(kept))
    return dists, direct, pth


def keep_elf(name):
    """ELF files that are data rather than executables of this image: module/source test fixtures."""
    return name.startswith("go/pkg/mod/") or "/testdata/" in name or "/fixtures/" in name


def go_buildinfo(data):
    """Return {path, mod, version} from a Go binary's embedded build info (module path + version), if present."""
    m = re.search(rb"path\t([^\n]+)\nmod\t([^\t\n]+)\t([^\t\n]+)", data)
    if not m:
        return None
    return {"path": m.group(1).decode(), "mod": m.group(2).decode(), "version": m.group(3).decode()}


def interpreter_for(site, dists_all):
    """Map a site-packages dir to the interpreter command that owns it (inside the arm64 image)."""
    m = re.match(r"^(.*)/lib/(python\d+\.\d+)/site-packages$", site)
    if m:
        prefix, py = m.groups()
        if prefix in ("usr/local", "usr"):
            return f"/{prefix}/bin/{py}"
        return f"/{prefix}/bin/python"  # a venv
    if site.startswith("usr/lib/python3/dist-packages"):
        return "/usr/bin/python3"
    m = re.match(r"^usr/local/lib/(python\d+\.\d+)/dist-packages$", site)
    if m:
        return f"/usr/bin/{m.group(1)}"
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("task")
    ap.add_argument("--no-build", action="store_true")
    ap.add_argument("--push", action="store_true")
    ap.add_argument("--keep-official", action="store_true")
    ap.add_argument("--reuse", action="store_true", help="reuse an existing ctx (only re-render the Dockerfile)")
    a = ap.parse_args()
    task = a.task
    name = B.rf_base_name(task)
    ref = f"{B.BASE_NS}:{name}"
    official = B.official_from(task)
    repo = re.search(r"swe_atlas_RF_(.+)_[0-9a-f]{24}_1\.0@", official).group(1)
    work = ROOT / "work" / "rf" / name
    ctx = work / "ctx"
    ctx.mkdir(parents=True, exist_ok=True)
    log = ROOT / "logs" / f"rfbase_{name}.log"
    t0 = time.time()
    report_p = work / "report.json"
    if a.reuse and report_p.exists() and (ctx / "transplant.tar").exists():
        report = json.load(open(report_p))
    else:
        report = {"task": task, "official": official, "repo": repo}
        if subprocess.run(["docker", "image", "inspect", official], capture_output=True).returncode:
            subprocess.run(["docker", "pull", "-q", "--platform", "linux/amd64", official], check=True,
                           stdout=subprocess.DEVNULL)
        fb = json.loads(subprocess.run([sys.executable, str(HERE / "find_base.py"), official], capture_output=True,
                                       text=True, check=True).stdout)
        if not fb["base"]:
            sys.exit(f"{task}: no base image matched: {fb['tried']}")
        report.update(base=fb["base"], base_layers=fb["matched_layers"], os=fb["os"])
        cfg, touched, dpkg_base, dpkg_final, apk_db = analyse(official, fb["matched_layers"], work)
        report["pkg_manager"] = "apk" if apk_db is not None else "apt"
        report["config"] = cfg.get("config", {})
        added = sorted(k for k in dpkg_final if k not in dpkg_base)
        apt_pkgs = sorted({re.sub(r":amd64$", "", k) for k in added if not X86_PKG.search(k)})
        report["apt"] = apt_pkgs
        report["apt_dropped_x86"] = sorted(k for k in added if X86_PKG.search(k))
        c = subprocess.run(["docker", "create", "--platform", "linux/amd64", official, "true"], capture_output=True,
                           text=True, check=True).stdout.strip()
        try:
            owned = apk_owned_from(apk_db) if apk_db is not None else dpkg_owned(c)
            dists, direct, pth = transplant(c, touched, owned, ctx, report)
        finally:
            subprocess.run(["docker", "rm", c], capture_output=True)
        report["python"] = {}
        for site, pk in sorted(dists.items()):
            editable = {}
            for dn, du in direct.items():
                if dn.startswith(site + "/"):
                    nm = re.match(r".*/([^/]+)-[^/-]+\.dist-info$", dn).group(1)
                    if (du.get("dir_info") or {}).get("editable") or du.get("url", "").startswith("file://"):
                        editable[nm] = du.get("url", "")
            report["python"][site] = {"interpreter": interpreter_for(site, dists), "dists": pk, "local": editable,
                                      "pth": pth.get(site, [])}
        (work / "image.tar").unlink(missing_ok=True)
        json.dump(report, open(report_p, "w"), indent=1)
    render(report, ctx, repo)
    print(f"{task}: base={report['base']} apt={len(report['apt'])} elf_dropped={len(report['elf_dropped'])} "
          f"python_sites={len(report['python'])} x86_text={len(report['x86_text_files'])} ({round(time.time()-t0)}s)",
          flush=True)
    if a.no_build:
        return
    for attempt in range(4):
        rc = subprocess.run(f"docker build --platform linux/arm64 --progress=plain -t {ref} {ctx} >> {log} 2>&1",
                            shell=True, env=B.ANON_ENV).returncode
        if rc == 0 or not re.search(r"429 Too Many|dial tcp|i/o timeout|TLS handshake", open(log, errors="replace").read()[-3000:]):
            break
        time.sleep(120 * (attempt + 1))
    if rc:
        sys.exit(f"{task}: base build failed, see {log}")
    print(f"{task}: built {ref}", flush=True)
    (ctx / "transplant.tar").unlink(missing_ok=True)  # regenerable from the official image; keeps the disk free
    if a.push:
        for attempt in range(4):
            if subprocess.run(f"docker push {ref} >> {log} 2>&1", shell=True).returncode == 0:
                break
            time.sleep(30 * (attempt + 1))
        else:
            sys.exit(f"{task}: push failed")
    if not a.keep_official:
        subprocess.run(["docker", "rmi", official], capture_output=True)


def render(report, ctx, repo):
    cfg = report["config"]
    L = [f"# arm64 reconstruction of {report['official']}",
         f"# generated by swe_interact/rf/build_rf_base.py; see report.json for what was transplanted/regenerated",
         f"# base: {report['base']} (pulled through mirror.gcr.io, identical digests, no Docker Hub pull quota)"
         if "/" not in report["base"].split(":")[0] else f"# base: {report['base']}",
         f"FROM {'mirror.gcr.io/library/' + report['base'] if '/' not in report['base'].split(':')[0] else report['base']}"]
    env = [e for e in cfg.get("Env") or []]
    eol_fix = None
    if re.search(r"\b(stretch|buster|bullseye)\b", report.get("os") or "") or re.search(r"(stretch|buster|bullseye)", report["base"]):
        # EOL Debian releases: bullseye left deb.debian.org in Aug 2026 (security pool already 404, not yet on
        # archive.debian.org); main/updates -> archive.debian.org, security -> snapshot.debian.org before the EOL
        eol_fix = ("RUN for f in /etc/apt/sources.list /etc/apt/sources.list.d/*; do [ -f \"$f\" ] && sed -i "
                 "-e 's|http://deb.debian.org/debian-security|http://snapshot.debian.org/archive/debian-security/20260801T000000Z|g' "
                 "-e 's|http://security.debian.org/debian-security|http://snapshot.debian.org/archive/debian-security/20260801T000000Z|g' "
                 "-e 's|http://deb.debian.org/debian|http://archive.debian.org/debian|g' \"$f\"; done; "
                 "echo 'Acquire::Check-Valid-Until \"false\";' > /etc/apt/apt.conf.d/99archive")
        L.append(eol_fix)
    if report["apt"] and report.get("pkg_manager") == "apk":
        L.append("RUN apk add --no-cache \\\n    " + " \\\n    ".join(report["apt"]))
    elif report["apt"]:
        L.append("RUN apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends \\\n    "
                 + " \\\n    ".join(report["apt"]) + " \\\n && rm -rf /var/lib/apt/lists/*")
    L.append("ADD transplant.tar /")
    if eol_fix:  # the transplant restores the official /etc/apt sources
        L.append(eol_fix)
    for e in env:
        k, v = e.split("=", 1)
        L.append(f"ENV {k}={json.dumps(v)}")
    # uv-managed interpreters / the verifier venv
    uv_sites = {s: d for s, d in report["python"].items() if s.startswith("opt/venv/")}
    for site, info in sorted(report["python"].items()):
        interp = info["interpreter"]
        if not interp or site in uv_sites:
            continue
        req = f"py-{re.sub(r'[^A-Za-z0-9]+', '_', site)}.txt"
        pins = [f"{n}=={v}" for n, v in sorted(info["dists"].items()) if n not in info["local"]]
        (ctx / req).write_text("\n".join(pins) + "\n")
        L.append(f"COPY {req} /tmp/{req}")
        pipi = (f"({interp} -m pip install --no-cache-dir --no-deps --break-system-packages -r /tmp/{req} "
                f"|| {interp} -m pip install --no-cache-dir --no-deps -r /tmp/{req})")
        # some pinned versions ship x86-64 wheels only (e.g. cryptography 2.9): build those from source
        L.append(f"RUN {pipi} || (apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y "
                 f"--no-install-recommends build-essential libssl-dev libffi-dev pkg-config cargo && {pipi})")
        for nm, url in info["local"].items():
            path = url.replace("file://", "") if url else ""
            if path:
                L.append(f"RUN {interp} -m pip install --no-cache-dir --no-deps --break-system-packages -e {path} "
                         f"|| {interp} -m pip install --no-cache-dir --no-deps -e {path}")
    if uv_sites:
        site, info = next(iter(uv_sites.items()))
        pyver = re.search(r"python(\d+\.\d+)", site).group(1)
        pins = [f"{n}=={v}" for n, v in sorted(info["dists"].items())]
        (ctx / "py-opt-venv.txt").write_text("\n".join(pins) + "\n")
        L.append("COPY py-opt-venv.txt /tmp/py-opt-venv.txt")
        L.append("RUN curl -LsSf https://astral.sh/uv/install.sh | sh && export PATH=/root/.local/bin:$PATH \\\n"
                 f" && rm -rf /opt/venv && uv venv /opt/venv --python {pyver} \\\n"
                 " && uv pip install --python /opt/venv/bin/python --no-deps -r /tmp/py-opt-venv.txt")
    rust = report.get("rust") or {}
    if rust.get("toolchains"):
        home = "/" + rust["home"]
        chome = "/" + rust.get("cargo_home", os.path.dirname(rust["home"]) + "/.cargo")
        tcs = [re.sub(r"-x86_64-unknown-linux-gnu$", "", t) for t in rust["toolchains"]]
        default = tcs[0]
        L.append(f"ENV RUSTUP_HOME={home} CARGO_HOME={chome}")
        L.append(f"RUN curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --no-modify-path "
                 f"--default-toolchain {default}" + "".join(f" && {chome}/bin/rustup toolchain install {t}" for t in tcs[1:]))
        for crate, info in sorted(((rust.get("crates2") or {}).get("installs") or {}).items()):
            m = re.match(r"^(\S+) (\S+) \((registry|git)\+([^)]+)\)$", crate)
            if m and m.group(3) == "registry":
                feats = info.get("features") or []
                flags = (" --no-default-features" if info.get("no_default_features") else "") + \
                        (f" --features {','.join(feats)}" if feats else "")
                L.append(f"RUN {chome}/bin/cargo install --locked {m.group(1)} --version {m.group(2)}{flags} "
                         f"|| {chome}/bin/cargo install {m.group(1)} --version {m.group(2)}{flags}")
    for path, gi in sorted((report.get("go_tools") or {}).items()):
        dest = "/" + os.path.dirname(path)
        if gi["version"] in ("(devel)", ""):
            # built from the task repository itself (e.g. /usr/local/bin/k6): rebuild it from the workspace
            wd = cfg.get("WorkingDir") or "/"
            L.append(f"RUN cd {wd} && go build -o /{path} {gi['path']}")
            continue
        L.append(f"RUN GOBIN={dest} CGO_ENABLED=0 go install {gi['path']}@{gi['version']}")
    recipe = HERE / "recipes" / f"{repo}.sh"
    if recipe.exists():
        shutil.copy(recipe, ctx / "recipe.sh")
        L.append("COPY recipe.sh /tmp/rf-recipe.sh")
        L.append("RUN bash -euxo pipefail /tmp/rf-recipe.sh")
    if cfg.get("WorkingDir"):
        L.append(f"WORKDIR {cfg['WorkingDir']}")
    if cfg.get("User"):
        L.append(f"USER {cfg['User']}")
    for k, v in (cfg.get("Labels") or {}).items():
        L.append(f"LABEL {json.dumps(k)}={json.dumps(v)}")
    L.append(f"ENTRYPOINT {json.dumps(cfg['Entrypoint'])}" if cfg.get("Entrypoint") else "ENTRYPOINT []")
    if cfg.get("Cmd"):
        L.append(f"CMD {json.dumps(cfg['Cmd'])}")
    (ctx / "Dockerfile").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
